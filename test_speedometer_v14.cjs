const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const html = fs.readFileSync('index.html', 'utf8');
const inline = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m => m[1]).filter(s => s.trim()).join('\n');
const fn = inline.match(/function speedDisplay\(mps\)\{[\s\S]*?\n(?=function updateSpeedMetrics)/);
assert(fn, 'speedDisplay function must exist');
const ctx = { speedUnit: 'kmh', Number };
vm.runInNewContext(fn[0], ctx);
assert.equal(ctx.speedDisplay(1), '3.6 km/h');
ctx.speedUnit = 'mph';
assert.equal(ctx.speedDisplay(1), '2.2 mph');
ctx.speedUnit = 'knots';
assert.equal(ctx.speedDisplay(1), '1.9 knots');
assert.equal(ctx.speedDisplay(NaN), '—');
assert(html.includes('<option value="kmh">km/h (kph)</option>'));
assert(html.includes('<option value="mph">mph</option>'));
assert(html.includes('<option value="knots">knots</option>'));
assert(html.includes("['mph','knots'].includes(localStorage.getItem('fieldtrack-speed-unit'))"));
assert(html.includes("speedUnit=['mph','knots'].includes(e.target.value)?e.target.value:'kmh'"));
console.log('PASS: km/h (kph), mph, and knots are selectable, correctly converted, and persisted.');
